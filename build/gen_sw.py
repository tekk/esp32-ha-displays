"""Generate site/sw.js – service worker for offline use after the first visit.
App shell (HTML, CSS, JS, vendor libs, fonts, core data) is precached; images, docs, manifests and the docs
index are cached on first use (cache-first). Data JSON uses stale-while-revalidate. VERSION changes whenever
a shell file changes, which drops old caches."""
import os, hashlib, glob, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, 'site')
SHELL_GLOBS = ['*.html', 'manifest.webmanifest', 'assets/css/*.css', 'assets/js/*.js', 'assets/vendor/*', 'assets/fonts/*.woff2', 'assets/fonts/fonts.css', 'assets/favicon.svg',
               'data/models.json', 'data/meta.json', 'data/search-models.json', 'data/archives.json', 'data/offline.json']

def main():
    files = sorted({os.path.relpath(f, SITE) for g in SHELL_GLOBS for f in glob.glob(os.path.join(SITE, g)) if os.path.isfile(f) and not f.endswith('404.html')})
    h = hashlib.sha1()
    for f in files:
        h.update(f.encode()); h.update(open(os.path.join(SITE, f), 'rb').read())
    ver = h.hexdigest()[:12]
    js = f"""/* generated by build/gen_sw.py – do not edit */
const VERSION = '{ver}';
const SHELL = 'shell-' + VERSION, RUNTIME = 'runtime-v1';
const PRECACHE = {json.dumps(['./'] + files)};
self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('shell-') && k !== SHELL).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', (e) => {{
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin) return;           // never touch cross-origin requests
  const scope = new URL(self.registration.scope).pathname;
  const rel = u.pathname.startsWith(scope) ? u.pathname.slice(scope.length) : u.pathname;
  if (/^(assets\\/img|docs\\/b|data\\/manifests|files)\\//.test(rel) || rel === 'data/search-docs.json' || rel === 'data/docs-snippets.json') {{
    e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((r) => {{
      if (r.ok && r.status === 200) {{ const cl = r.clone(); caches.open(RUNTIME).then((c) => c.put(e.request, cl)); }}
      return r;
    }})));
    return;
  }}
  // shell + data: cache first (ignoring query string), refresh in background
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => {{
    const net = fetch(e.request).then((r) => {{ if (r.ok && r.status === 200) {{ const cl = r.clone(); caches.open(SHELL).then((c) => c.put(e.request, cl)); }} return r; }}).catch(() => hit);
    return hit || net;
  }}));
}});
"""
    open(os.path.join(SITE, 'sw.js'), 'w').write(js)
    print('sw.js', ver, len(files), 'precached files')

if __name__ == '__main__':
    main()
