"""Vendor self-hosted web fonts into site/assets/fonts (no Google Fonts / CDN at runtime).
Roboto Condensed, Montserrat, JetBrains Mono: from npm @fontsource/* (OFL-1.1), latin + latin-ext subsets.
Meslo LG M: from github.com/andreberg/Meslo-Font (Apache-2.0), TTF -> WOFF2 via fontTools (needs brotli)."""
import os, re, shutil, subprocess, io, zipfile, urllib.request
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'site/assets/fonts')
NM = os.path.join(ROOT, 'node_modules/@fontsource')
FAMS = {'roboto-condensed': ('Roboto Condensed', [400, 500, 700]), 'montserrat': ('Montserrat', [400, 500, 600, 700]), 'jetbrains-mono': ('JetBrains Mono', [400, 700])}
MESLO = 'https://raw.githubusercontent.com/andreberg/Meslo-Font/master/dist/v1.2.1/Meslo%20LG%20v1.2.1.zip'

def main():
    os.makedirs(OUT, exist_ok=True)
    css = ['/* self-hosted fonts – generated by build/fonts.py */']
    for pkg, (fam, weights) in FAMS.items():
        for w in weights:
            for sub in ('latin-ext', 'latin'):
                allcss = open(os.path.join(NM, pkg, f'{w}.css')).read()
                block = re.search(r'/\* [a-z-]+-' + re.escape(sub) + rf'-{w}-normal \*/.*?\}}', allcss, re.S).group(0)
                ur = re.search(r'unicode-range:\s*([^;]+);', block).group(1)
                fn = f'{pkg}-{sub}-{w}-normal.woff2'
                shutil.copyfile(os.path.join(NM, pkg, 'files', fn), os.path.join(OUT, fn))
                css.append(f"@font-face{{font-family:'{fam}';font-style:normal;font-display:swap;font-weight:{w};src:url({fn}) format('woff2');unicode-range:{ur};}}")
        shutil.copyfile(os.path.join(NM, pkg, 'LICENSE'), os.path.join(OUT, f'LICENSE-{pkg}.txt'))
    # Meslo
    need = [('MesloLGM-Regular', 400), ('MesloLGM-Bold', 700)]
    if not all(os.path.exists(os.path.join(OUT, n + '.woff2')) for n, _ in need):
        from fontTools.ttLib import TTFont
        z = zipfile.ZipFile(io.BytesIO(urllib.request.urlopen(MESLO, timeout=60).read()))
        for n, _ in need:
            name = next(x for x in z.namelist() if x.endswith(n + '.ttf'))
            f = TTFont(io.BytesIO(z.read(name)))
            f.flavor = 'woff2'
            f.save(os.path.join(OUT, n + '.woff2'))
    for n, w in need:
        css.append(f"@font-face{{font-family:'Meslo LG M';font-style:normal;font-display:swap;font-weight:{w};src:url({n}.woff2) format('woff2');}}")
    open(os.path.join(OUT, 'LICENSE-meslo.txt'), 'w').write('Meslo LG – Copyright (c) 2009-2013 André Berg. Derived from Bitstream Vera Sans Mono / Menlo.\nLicensed under the Apache License, Version 2.0 – http://www.apache.org/licenses/LICENSE-2.0\nSource: https://github.com/andreberg/Meslo-Font\n')
    open(os.path.join(OUT, 'fonts.css'), 'w').write('\n'.join(css) + '\n')
    print('fonts:', len(os.listdir(OUT)), 'files', sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT)) // 1024, 'KB')

if __name__ == '__main__':
    main()
